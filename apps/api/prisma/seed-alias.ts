/**
 * Банк слов для Библейского Alias.
 *
 * Правила, по которым он собран:
 *
 *  - **Одно слово или короткое словосочетание.** Alias — игра про
 *    объяснение понятия, а не фразы. «Блудный сын» проходит, «И сказал Бог
 *    да будет свет» — нет.
 *  - **Уровень описывает слово, а не игрока.** «Легко» — школьный уровень
 *    и общая культура, «Средне» — знакомо тому, кто был на разборах,
 *    «Сложно» — начинается спорт.
 *  - **`gloss` — ровно одна строка.** Она читается вслух между раундами,
 *    пока компания ждёт следующего хода. Абзац здесь никто не дочитает.
 *  - **Ссылка разобрана на части, а не строкой.** `ref: [книга, глава,
 *    стих]` проверяется при заливке по настоящему тексту Синодального
 *    перевода: если стиха нет, сид падает. Строку так не проверить, и
 *    опечатка в сокращении книги ушла бы в продакшн незамеченной.
 *  - **Ссылка только там, где она однозначна.** У сквозных понятий
 *    («завет», «пророк», «покаяние») одного честного места нет, и выдумать
 *    его хуже, чем оставить пусто. Пустая ссылка — это не пробел в работе,
 *    а отказ соврать.
 *
 * Отдельно про категорию `IDIOM` — «Крылатые слова». Это вход в игру для
 * тех, кто Библию не читал: «козёл отпущения», «умыть руки», «манна
 * небесная» — слова, которыми человек пользуется каждый день, не зная,
 * откуда они. Такая компания начинает с категории, где заведомо всё знает,
 * и по ходу узнаёт, что всё это время цитировала Писание. Это лучший
 * первый раунд, который здесь можно предложить.
 *
 * Запуск: `pnpm --filter @bible-arena/api exec ts-node prisma/seed-alias.ts`
 */
