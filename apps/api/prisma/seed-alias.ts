/**
 * Проверяет банк до единой записи в базу. Всё, что здесь ловится, — это
 * ошибки, которые в игре выглядели бы как враньё: две карточки с одним
 * словом, пояснение в три строки или ссылка на стих, которого нет.
 */
async function validate(): Promise<void> {
  const problems: string[] = [];

  const seen = new Map<string, number>();
  for (const entry of WORDS) {
    seen.set(entry.word, (seen.get(entry.word) ?? 0) + 1);
    if (entry.gloss.length > 90) {
      problems.push(
        `«${entry.word}»: пояснение длиннее 90 символов (${entry.gloss.length})`,
      );
    }
    if (
      !entry.gloss.endsWith('.') &&
      !entry.gloss.endsWith('…') &&
      !entry.gloss.endsWith('»') &&
      !entry.gloss.endsWith('?')
    ) {
      problems.push(`«${entry.word}»: пояснение без завершающего знака`);
    }
  }
  for (const [word, count] of seen) {
    if (count > 1) problems.push(`«${word}»: встречается ${count} раза`);
  }

  // Ссылки сверяем с реальным текстом: книга, глава и стих должны
  // существовать. Это единственная проверка, которую нельзя сделать
  // «на глаз», и единственная, ошибка в которой видна пользователю.
  const refs = WORDS.filter((entry) => entry.ref);
  const found = await prisma.bibleVerse.findMany({
    where: {
      OR: refs.map((entry) => ({
        bookId: entry.ref![0],
        chapter: entry.ref![1],
        verse: entry.ref![2],
      })),
    },
    select: { bookId: true, chapter: true, verse: true },
  });
  const existing = new Set(
    found.map((v) => `${v.bookId}:${v.chapter}:${v.verse}`),
  );
  for (const entry of refs) {
    const [bookId, chapter, verse] = entry.ref!;
    if (!existing.has(`${bookId}:${chapter}:${verse}`)) {
      problems.push(
        `«${entry.word}»: стиха ${bookId} ${chapter}:${verse} нет в тексте`,
      );
    }
  }

  if (problems.length > 0) {
    console.error(`Банк не прошёл проверку (${problems.length}):`);
    for (const problem of problems) console.error(`  — ${problem}`);
    throw new Error('Банк слов содержит ошибки, ничего не записано');
  }
}

async function main(): Promise<void> {
  console.log(`Слов в наборе: ${WORDS.length}`);

  const verseCount = await prisma.bibleVerse.count();
  if (verseCount === 0) {
    throw new Error(
      'В базе нет текста Библии — сначала `pnpm --filter @bible-arena/api prisma:seed-bible`, ' +
        'иначе ссылки нечем проверить.',
    );
  }
  await validate();

  // upsert, а не пересоздание: сид запускают повторно, а партии ссылаются на
  // слова по id — пересоздание порвало бы эти ссылки без всякой пользы.
  let created = 0;
  let updated = 0;
  for (const entry of WORDS) {
    const fields = {
      difficulty: entry.difficulty,
      category: entry.category,
      testament: entry.testament,
      gloss: entry.gloss,
      refBookId: entry.ref?.[0] ?? null,
      refChapter: entry.ref?.[1] ?? null,
      refVerse: entry.ref?.[2] ?? null,
    };
    const existing = await prisma.aliasWord.findUnique({
      where: { word: entry.word },
      select: { id: true },
    });
    await prisma.aliasWord.upsert({
      where: { word: entry.word },
      create: { word: entry.word, ...fields },
      update: fields,
    });
    if (existing) {
      updated += 1;
    } else {
      created += 1;
    }
  }

  const byDifficulty = await prisma.aliasWord.groupBy({
    by: ['difficulty'],
    _count: { _all: true },
  });
  const byCategory = await prisma.aliasWord.groupBy({
    by: ['category'],
    _count: { _all: true },
  });
  const withoutReference = await prisma.aliasWord.count({
    where: { refBookId: null },
  });

  console.log(`Добавлено: ${created}, обновлено: ${updated}`);
  console.log('По уровню:');
  for (const row of byDifficulty) {
    console.log(`  ${row.difficulty}: ${row._count._all}`);
  }
  console.log('По категории:');
  for (const row of byCategory) {
    console.log(`  ${row.category}: ${row._count._all}`);
  }
  console.log(`Без ссылки на стих (сквозные понятия): ${withoutReference}`);
}

main()
  .catch((error) => {
    console.error(error);
    process.exit(1);
  })
  .finally(() => void prisma.$disconnect());
