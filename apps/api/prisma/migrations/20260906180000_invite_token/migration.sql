-- Неугадываемый ключ пригласительной ссылки.
--
-- До этого в ссылке стоял сам `id` пользователя, а параметр запуска
-- приходит от клиента: подставив чужой `id`, свежий аккаунт получал
-- взаимную дружбу с любым игроком без его согласия.
--
-- Заводится лениво, при первом запросе ссылки, поэтому колонка обнуляемая.
ALTER TABLE "users" ADD COLUMN "inviteToken" TEXT;
CREATE UNIQUE INDEX "users_inviteToken_key" ON "users"("inviteToken");
