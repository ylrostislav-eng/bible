-- `musicInGames` прожил меньше суток и удаляется: он решал вопрос «где
-- музыке молчать», а владелец решил иначе — играет везде, а мешает она
-- или нет, человек решает громкостью. Одна общая ручка на отклики и
-- музыку заставляла выбирать между «громко» и «глухо»: музыка звучит
-- постоянно, щелчок — сотую долю секунды.
ALTER TABLE "users" DROP COLUMN "musicInGames";
ALTER TABLE "users" ADD COLUMN "musicVolume" INTEGER NOT NULL DEFAULT 60;
