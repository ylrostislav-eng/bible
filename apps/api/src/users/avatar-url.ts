/**
 * Откуда разрешено брать аватар.
 *
 * ## Что было не так
 *
 * Поле принимало любой `https`-адрес, и этот адрес показывался всем
 * остальным игрокам — в списке лидеров, в друзьях, в чате. То есть любой
 * желающий мог поставить себе «аватаром» ссылку на свой сервер, попасть в
 * общий список и собирать IP-адреса, время захода и модель устройства
 * каждого, кто этот список открыл. Картинку при этом никто не видел —
 * достаточно было отдать прозрачный пиксель.
 *
 * Для приложения, где играют дети, это худший вид утечки: она незаметна,
 * не требует ничего от жертвы и выдаёт данные, которых мы сами про
 * игроков не храним.
 *
 * Вторая беда мельче, но реальнее: по такой ссылке можно отдать что
 * угодно, и модерации изображений у нас нет.
 *
 * ## Почему список доменов, а не проверка «это картинка»
 *
 * Проверять содержимое бесполезно: сервер отдаёт картинку нам и что
 * угодно — браузерам игроков. Помогает только запрет ходить на чужие
 * адреса вообще.
 *
 * Домены — телеграмовские, потому что настоящий аватар и так приходит
 * оттуда: его присылает сам Telegram в `photo_url` при входе. Ручной ввод
 * ссылки после этого нужен ровно для одного — вставить другую свою
 * телеграмовскую картинку.
 */
const ALLOWED_AVATAR_HOSTS = [
  't.me',
  'telegram.org',
  'telegram.me',
  // Аватары приходят с раздачи Telegram, и поддомен там меняется от
  // датацентра к датацентру (`cdn1`, `cdn4`, …), поэтому по суффиксу.
  'telegram-cdn.org',
  'telesco.pe',
  'cdn-telegram.org',
];

/**
 * Разрешён ли адрес аватара.
 *
 * `null` (аватара нет) — разрешён: это способ его убрать.
 */
export function isAllowedAvatarUrl(url: string | null | undefined): boolean {
  if (url === null || url === undefined) return true;

  let parsed: URL;
  try {
    parsed = new URL(url);
  } catch {
    return false;
  }

  if (parsed.protocol !== 'https:') return false;

  const host = parsed.hostname.toLowerCase();
  return ALLOWED_AVATAR_HOSTS.some(
    // Точное совпадение или поддомен — и обязательно через точку:
    // `endsWith('telegram.org')` без неё пропустил бы `nottelegram.org`.
    (allowed) => host === allowed || host.endsWith(`.${allowed}`),
  );
}
