import { createHash } from 'node:crypto';

/**
 * День игрока и выбор того, что ему сегодня достанется.
 *
 * Ежедневных игр в приложении уже несколько, и все они отвечают на два
 * одинаковых вопроса: какой сейчас день у этого человека и какой элемент
 * банка ему сегодня показать. Держать ответы порознь — верный способ
 * однажды получить два разных «сегодня» на одном экране.
 */

/**
 * Локальная дата игрока в виде полуночи по UTC — тот же приём, что у серии
 * дней, и по той же причине: день должен меняться в его полночь, а не в
 * чьей-то чужой.
 *
 * Следствие, которое стоит понимать: у двух друзей из разных часовых поясов
 * задание в один и тот же момент может отличаться. Это честнее обратного
 * варианта — общего для всех дня по UTC, при котором у половины аудитории
 * «сегодняшнее» задание менялось бы посреди дня.
 */
export function localDate(timezoneOffsetMinutes: number): Date {
  const shifted = new Date(Date.now() - timezoneOffsetMinutes * 60_000);
  return new Date(
    Date.UTC(
      shifted.getUTCFullYear(),
      shifted.getUTCMonth(),
      shifted.getUTCDate(),
    ),
  );
}

/** `ГГГГ-ММ-ДД` — то, что уезжает клиенту. */
export function dateLabel(date: Date): string {
  return date.toISOString().slice(0, 10);
}

/**
 * Позиция дня в банке. Вынесена отдельной чистой функцией не ради красоты:
 * обещание «сколько слов в банке, столько дней без повтора» иначе никак не
 * проверить, а необещанное поведение выбора заметят только через год.
 */
export function dayIndex(date: Date, bankSize: number): number {
  const dayNumber = Math.floor(date.getTime() / 86_400_000);
  // Остаток может быть отрицательным для дат до 1970 — на практике нет, но
  // привести к неотрицательному дешевле, чем потом это ловить.
  return ((dayNumber % bankSize) + bankSize) % bankSize;
}

/**
 * Устойчивая псевдослучайная перестановка банка: сортировка по хешу от
 * ключа.
 *
 * Не «случайный элемент по хешу даты», потому что тогда задания
 * повторялись бы задолго до того, как банк кончится — парадокс дней
 * рождения бьёт по этому больно. Так цикл ровно в длину банка.
 */
export function shuffledByKey<T>(items: T[], keyOf: (item: T) => string): T[] {
  return [...items].sort((a, b) =>
    createHash('sha256')
      .update(keyOf(a))
      .digest('hex')
      .localeCompare(createHash('sha256').update(keyOf(b)).digest('hex')),
  );
}
