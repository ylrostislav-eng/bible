import type { PrismaClient } from '@prisma/client';

/**
 * Подбор соперника: как найти незнакомца, а не только друга по коду.
 *
 * ## Очередь — это ожидающие партии, а не отдельная таблица
 *
 * Соблазн завести «очередь» отдельной сущностью велик, но она тут же
 * начинает жить своей жизнью: билет есть, партии нет; партия есть, билет
 * остался; двое взяли один билет. Всё это надо мирить.
 *
 * Ожидающая партия сама по себе — уже билет: она существует, у неё есть
 * владелец, её видно, и её уборка уже написана. Поэтому «встать в поиск» —
 * это найти чужую ожидающую партию и войти в неё, а если такой нет —
 * создать свою и ждать. Никакой второй сущности.
 *
 * ## Почему возможна гонка и почему это не страшно
 *
 * Двое могут выбрать одну и ту же чужую партию одновременно. Побеждает
 * тот, чей атомарный захват прошёл (`updateMany` с условием «ещё ждёт»);
 * второй получает отказ и пробует следующую. Поэтому здесь цикл попыток, а
 * не один запрос: без него проигравший гонку остался бы ни с чем, хотя
 * рядом могла ждать другая партия.
 */

/** Сколько раз пробовать сесть в чужую партию, прежде чем создать свою. */
export const MATCH_ATTEMPTS = 3;

/**
 * Кого нельзя подсаживать друг к другу.
 *
 * Личный чёрный список хранится в `RoomBan` — исторически он про комнаты,
 * но профиль и чат используют его же как «я не хочу иметь дела с этим
 * человеком». Подбор обязан учитывать его в обе стороны: и тех, кого я
 * заблокировал, и тех, кто заблокировал меня. Второе не менее важно —
 * иначе заблокировавший всё равно окажется со мной в партии, просто по
 * моей инициативе.
 */
export async function blockedWith(
  prisma: PrismaClient,
  userId: string,
): Promise<string[]> {
  const bans = await prisma.roomBan.findMany({
    where: { OR: [{ leaderId: userId }, { bannedUserId: userId }] },
    select: { leaderId: true, bannedUserId: true },
  });
  const others = new Set<string>();
  for (const ban of bans) {
    others.add(ban.leaderId === userId ? ban.bannedUserId : ban.leaderId);
  }
  return [...others];
}
