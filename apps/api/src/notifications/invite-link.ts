import type { ConfigService } from '@nestjs/config';

/**
 * Ссылка-приглашение: как сделать, чтобы она открывала игру, а не бота.
 *
 * ## Три вида ссылок Telegram, и только два из них работают
 *
 * 1. `t.me/<бот>/<короткое_имя>?startapp=…` — **прямая ссылка на
 *    мини-приложение**. Открывает игру в одно нажатие. Короткое имя
 *    заводится в BotFather командой `/newapp`; без него такой ссылки не
 *    существует.
 * 2. `t.me/<бот>?startapp=…` и `t.me/<бот>/app?startapp=…` — то же самое,
 *    но для **Main Mini App**. Работает, только если приложение назначено
 *    главным в BotFather.
 * 3. `t.me/<бот>?start=…` — открывает **чат с ботом** и кнопку «Старт».
 *    Приложение не открывает, зато нажатие «Старт» создаёт переписку — и
 *    после него боту разрешено писать этому человеку.
 *
 * ## Почему здесь именно так
 *
 * Раньше ссылка всегда строилась по второму виду — и молча не работала:
 * Main Mini App не был назначен, поэтому нажатие открывало профиль бота и
 * на этом всё заканчивалось. Ошибки при этом нет ни на одной стороне,
 * поэтому найти это можно было только глазами (_и нашлось так же — по
 * жалобе владельца на уведомление, которое «не открывает приложение»_).
 *
 * Теперь: если короткое имя приложения задано (`TELEGRAM_MINI_APP_SHORT_NAME`)
 * — строим первый вид, самый прямой. Если нет — третий: пусть человек
 * попадёт хотя бы в бота, который ответит кнопкой «Открыть игру»
 * (`TelegramUpdatesService`). Второй вид не используем вовсе: он выглядит
 * как первый, а ломается молча.
 */
export function buildInviteLink(
  botUsername: string,
  inviteToken: string,
  config: Pick<ConfigService, 'get'>,
): string {
  const shortName = (
    config.get<string>('TELEGRAM_MINI_APP_SHORT_NAME') ?? ''
  ).trim();

  return shortName
    ? `https://t.me/${botUsername}/${shortName}?startapp=ref_${inviteToken}`
    : `https://t.me/${botUsername}?start=ref_${inviteToken}`;
}

/**
 * Открывает ли эта ссылка приложение сразу.
 *
 * Нужно интерфейсу: рядом со ссылкой честно пишем, что откроется — игра
 * или бот. Обещать «откроется игра», когда откроется бот, нельзя: человек
 * зовёт по этой ссылке друга и объясняет ему, что будет дальше.
 */
export function inviteLinkOpensApp(
  config: Pick<ConfigService, 'get'>,
): boolean {
  return Boolean(
    (config.get<string>('TELEGRAM_MINI_APP_SHORT_NAME') ?? '').trim(),
  );
}
