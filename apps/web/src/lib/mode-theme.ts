/**
 * Лицо режима: свой оттенок у каждого экрана.
 *
 * ## Почему цвет живёт только в фоне и в кольце иконки
 *
 * Соблазн был раскрасить режимы целиком — свои кнопки, свои заголовки.
 * Так делать нельзя: палитра приложения построена вокруг одного янтаря,
 * и шесть равноправных цветов превратили бы её в радугу, где ничто не
 * выделяется, потому что выделено всё.
 *
 * Поэтому цвет режима появляется в двух местах и очень тихо: мягкое
 * сияние вверху экрана и кольцо вокруг иконки. Этого хватает, чтобы
 * дуэль ощущалась холоднее одиночной игры, а Alias — вечернее; всё
 * остальное — общий язык приложения.
 *
 * ## Почему по началу адреса, а не по имени режима
 *
 * У экранов бывают вложенные адреса, и список точных совпадений
 * пришлось бы дополнять при каждом новом экране. То же решение, что и у
 * музыки: сопоставление по префиксу.
 */

export interface ModeTheme {
  /** Оттенок режима. */
  accent: string;
  /** Что рассказывает сияние: чем ниже, тем спокойнее экран. */
  glow: number;
}

/** Общий янтарь: главная, профиль, друзья, настройки. */
export const DEFAULT_THEME: ModeTheme = { accent: '#e8b04b', glow: 0.14 };

/**
 * Порядок важен: `/play/duel` должен найтись раньше, чем `/play`.
 * Массив, а не объект, именно поэтому — у объекта порядок ключей
 * читается как случайность, а здесь он часть смысла.
 */
const THEMES: { prefix: string; theme: ModeTheme }[] = [
  // Соперничество холоднее: синий рядом с янтарём читается как «другая
  // сторона», а не как ещё один тёплый экран.
  { prefix: '/play/duel', theme: { accent: '#6f9fe0', glow: 0.18 } },
  { prefix: '/hot-cold', theme: { accent: '#f4a259', glow: 0.19 } },
  // Комната — это много людей сразу, и зелёный тут единственный цвет,
  // который не спорит ни с янтарём, ни с синим дуэли.
  { prefix: '/play/room', theme: { accent: '#64c9a4', glow: 0.17 } },
  // Alias играют вечером и вокруг стола — отсюда сиреневый.
  { prefix: '/play/alias', theme: { accent: '#b18cf0', glow: 0.18 } },
  { prefix: '/play/solo', theme: { accent: '#e8b04b', glow: 0.16 } },
  // Чтение: сияние слабее всех остальных. Экран, на котором читают,
  // должен быть тише экрана, на котором играют.
  { prefix: '/learn', theme: { accent: '#86b6d9', glow: 0.09 } },
  { prefix: '/daily', theme: { accent: '#e8b04b', glow: 0.16 } },
  { prefix: '/tournaments', theme: { accent: '#d9a066', glow: 0.14 } },
];

export function modeTheme(pathname: string | null): ModeTheme {
  if (!pathname) return DEFAULT_THEME;
  return THEMES.find(({ prefix }) => pathname.startsWith(prefix))?.theme ?? DEFAULT_THEME;
}
