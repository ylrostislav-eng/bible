/**
 * Имя игрока для показа. Пустого имени в списках быть не должно.
 *
 * Никнейм появляется не сразу: человек, пришедший по ссылке-приглашению,
 * становится другом **до** онбординга — так и задумано, иначе позвавший не
 * увидит, что его звонок дошёл. Но между входом и вводом имени аккаунт
 * существует безымянным, и в списке друзей это рисовалось пустой строкой:
 * человек есть, а кто — непонятно.
 *
 * Показать вместо этого имя из Telegram нельзя: оно не уходит с сервера
 * другим игрокам, и это отдельное решение, а не недосмотр.
 */
export function playerName(nickname: string | null | undefined): string {
  return nickname ?? 'Игрок';
}

