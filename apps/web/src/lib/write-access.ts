'use client';

import { requestWriteAccess } from '@telegram-apps/sdk-react';

/**
 * Спросить у Telegram разрешение писать этому человеку в личные сообщения.
 *
 * ## Зачем отдельная просьба
 *
 * Открытие мини-приложения переписки с ботом **не создаёт**: человек может
 * играть месяцами, а бот всё это время не имеет права ему написать. Наши
 * уведомления («вас вызвали на дуэль», напоминание про серию) при этом
 * никуда не деваются — они просто никому не доходят, и молча: Telegram
 * отвечает отказом, а игрок уверен, что уведомления у него включены,
 * потому что тумблер в настройках включён.
 *
 * `requestWriteAccess` показывает родное окно Telegram «Разрешить боту
 * писать вам?». Оно и есть то самое «взаимодействие с ботом», без которого
 * писать нельзя, — но, в отличие от кнопки «Старт» в чате, спрашивается не
 * уходя из игры.
 *
 * ## Что возвращает
 *
 * `true` — разрешили. Всё остальное (закрыли окно, старый клиент, запуск
 * не из Telegram) — `false`, и различать эти случаи незачем: спросить
 * повторно можно в обоих, а записать отказ нельзя ни в одном — «закрыл, не
 * читая» неотличимо от «не хочу», и приняв первое за второе, мы больше не
 * спросим никогда.
 *
 * Ответ Telegram отдаёт **приложению**, не серверу, поэтому разрешение
 * приходится потом отдельно отнести на сервер (`POST /users/me/write-access`).
 * Другого пути нет: `initData` с флагом `allows_write_to_pm` выдан на
 * запуске и до следующего не изменится, а следующий может быть через
 * неделю.
 */
export async function askWriteAccess(): Promise<boolean> {
  try {
    if (!requestWriteAccess.isAvailable()) return false;
    return (await requestWriteAccess()) === 'allowed';
  } catch {
    // Окно уже открыто, метод не поддержан клиентом, человек закрыл
    // приложение — ни один случай не стоит того, чтобы уронить экран,
    // с которого спросили.
    return false;
  }
}
