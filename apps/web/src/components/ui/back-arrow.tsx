import Link from 'next/link';

/**
 * Стрелка «назад» в шапке экрана — **вдобавок** к нижнему выходу.
 *
 * ## Где применяется и где нет
 *
 * Основной выход с любого экрана — `ScreenBack` внизу: телефон держат
 * одной рукой, и палец достаёт нижнюю треть. Раньше на части экранов
 * выход был только здесь, в шапке, и приложение выглядело собранным из
 * кусков — где-то надпись внизу, где-то стрелка в углу.
 *
 * Остался этот компонент ровно там, где нижнего выхода недостаточно: в
 * «Изучении» список глав и текст главы прокручиваются на несколько
 * экранов, и выход, до которого надо долистать, выходом быть перестаёт.
 * Там стрелка стоит вместе с нижним «Назад», а не вместо него.
 *
 * Заводить её на новом экране — почти всегда ошибка. Сначала `ScreenBack`.
 *
 * Ведёт по прямому адресу, а не `history.back()`: экран можно открыть по
 * ссылке от друга, и тогда «назад» увело бы из приложения совсем.
 */
export function BackArrow({
  href,
  label,
}: {
  href: string;
  /** Куда именно ведёт — читается озвучкой вместо голого «назад». */
  label: string;
}) {
  return (
    <Link
      href={href}
      aria-label={label}
      className="glass flex h-9 w-9 shrink-0 items-center justify-center rounded-full text-text-secondary transition hover:text-text-primary"
    >
      ←
    </Link>
  );
}
