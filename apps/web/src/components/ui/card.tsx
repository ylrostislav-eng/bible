import clsx from 'clsx';
import type { HTMLAttributes } from 'react';

/**
 * Карточка — непрозрачная, и это решение, а не недоделка.
 *
 * Соблазн был сделать её стеклянной вслед за иконками: тогда обои режима
 * просвечивали бы через весь экран, а не только в зазорах. Посчитали:
 * при 72 % плотности над светлым местом кадра приглушённый текст
 * (`--color-text-muted`) падает с 4.9:1 примерно до 2.6:1, при 85 % — до
 * 3.5:1. Порог для мелкого текста — 4.5:1, и он не проходит ни при какой
 * разумной плотности. Контраст этого текста уже возвращали отдельной
 * работой, и менять его обратно на красоту нельзя.
 *
 * Стеклянный язык карточка всё же получает — но краем, а не прозрачностью:
 * светлый блик по верхней грани и мягкая тень наружу (`.glass-edge`).
 * Этого хватает, чтобы она читалась предметом над картинкой, а не
 * заплаткой на ней.
 */
export function Card({ className, ...props }: HTMLAttributes<HTMLDivElement>) {
  return (
    <div
      className={clsx('glass-edge flex rounded-2xl border border-border bg-surface p-4', className)}
      {...props}
    />
  );
}
