import clsx from 'clsx';
import type { HTMLAttributes } from 'react';

/**
 * Карточка — стекло, сквозь которое видно обои режима.
 *
 * ## Отброшенное решение и почему оно было неверным
 *
 * Сначала карточка осталась непрозрачной, и отказ был обоснован
 * расчётом: при 72 % плотности над светлым местом кадра приглушённый
 * текст падает с 4.9:1 до ~2.6:1, при 85 % — до 3.5:1, порог 4.5:1.
 * Арифметика верна, вывод «прозрачных карточек с текстом не бывает» —
 * нет.
 *
 * Неверным был приём, а не цель. Держать контраст плотностью
 * действительно нельзя, но плотность — не единственный рычаг: помогает
 * сочетание умеренного размытия, осветлённого текста поверх стекла и
 * точечного затемнения обоев там, где под карточками свет. Подробности,
 * числа и отброшенные попытки — у `.glass-card` в `globals.css`.
 *
 * ## Что здесь легко сломать
 *
 * Заменить `.glass-card` на `.glass`: они выглядят похоже, но у `.glass`
 * нет гашения, и он рассчитан на иконки, под которыми текста нет.
 */
export function Card({ className, ...props }: HTMLAttributes<HTMLDivElement>) {
  return <div className={clsx('glass-card flex rounded-2xl p-4', className)} {...props} />;
}
