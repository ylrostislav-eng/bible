'use client';

import { usePathname } from 'next/navigation';
import { useEffect } from 'react';
import { ALL_BACKGROUNDS, backgroundUrl, screenBackground } from '@/lib/screen-background';

/**
 * Обои экрана — своя картинка у каждого режима.
 *
 * ## Откуда взялось
 *
 * Кнопки на коротких экранах опустили к большому пальцу, и между шапкой
 * и ними образовалась дыра в полэкрана. Сначала её закрывала одна и та
 * же приглушённая лампа на всех экранах (`ScreenArt`) — заполняло, но
 * выглядело однообразно и сухо. Обои закрывают ту же пустоту тем, что
 * рассказывает про режим: дуэль, комната, чтение выглядят по-разному, не
 * тратя ни строчки текста.
 *
 * ## Почему `<img>`, а не `background-image`
 *
 * Сначала было `background-image` в инлайн-стиле, и картинка приезжала
 * последней — заметно позже всего остального. Причина не в весе файла
 * (40–70 КБ), а в том, **когда браузер о нём узнаёт**: адрес в стиле
 * появляется только после того, как отработал JS, то есть предзагрузчик
 * браузера, который читает HTML ещё до скриптов, о картинке не знает
 * вовсе. Обычный `<img>` попадает в статическую разметку страницы, и его
 * находят при разборе документа — на том же шаге, что и всё остальное.
 *
 * Второй половиной той же беды был `AuthGate`: слой лежал внутри него, а
 * тот до конца входа рендерит один спиннер. Картинка не начинала
 * грузиться, пока не сходит в Telegram и на наш сервер. Теперь слой
 * висит снаружи входа (см. `app/(main)/layout.tsx`).
 *
 * ## Почему поверх лежит затемнение
 *
 * Гарантия контраста: сверху заголовок, снизу кнопки и навигация, и они
 * должны читаться независимо от того, что нарисовано на кадре. Проверять
 * это глазами на каждой новой картинке — работа, которая обязательно
 * однажды не будет сделана.
 */
export function ScreenBackground() {
  const { file, topFade, midFade } = screenBackground(usePathname());

  useEffect(() => {
    // Остальные восемь картинок берутся в простое — после того, как
    // страница отрисовалась и текущая обои уже загружены.
    //
    // Раньше здесь предзагрузки не было вовсе, из соображения «не тратить
    // чужой трафик на экран, куда человек может не зайти». Соображение
    // оказалось дороже пользы: при переходе в режим картинка приезжала
    // отдельно от содержимого, и переход выглядел недогруженным. Все
    // девять весят 424 КБ — меньше одной обычной фотографии, — а
    // `requestIdleCallback` тратит их тогда, когда браузеру всё равно
    // нечем заняться, и потому не отнимает скорость у первого экрана.
    const load = () => {
      for (const other of ALL_BACKGROUNDS) {
        if (other === file) continue;
        const img = new Image();
        img.src = backgroundUrl(other);
      }
    };

    // Safari научился `requestIdleCallback` только в 16.4 — запасной путь
    // нужен ради старых телефонов, а не ради красоты.
    if (typeof requestIdleCallback === 'function') {
      const id = requestIdleCallback(load, { timeout: 4000 });
      return () => cancelIdleCallback(id);
    }
    const id = setTimeout(load, 2000);
    return () => clearTimeout(id);
    // Список зависимостей пуст намеренно: предзагрузка нужна один раз за
    // запуск приложения, а не на каждом переходе между режимами.
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  return (
    <div aria-hidden className="pointer-events-none fixed inset-0 -z-20 overflow-hidden">
      {/* `key` по имени файла: смена режима — это новый слой, который
          проявляется, а не картинка, которая подменяется рывком. Внутри
          одного режима ключ не меняется, и появления нет. */}
      {/* eslint-disable-next-line @next/next/no-img-element */}
      <img
        key={file}
        src={backgroundUrl(file)}
        alt=""
        // `high` — потому что это фон всего экрана, а не украшение в
        // углу: без явного приоритета браузер ставит картинку в очередь
        // после скриптов, и она снова приезжает последней.
        fetchPriority="high"
        decoding="async"
        className="screen-bg-in absolute inset-0 h-full w-full object-cover"
      />
      {/* Проценты — те же зоны, по которым рисовались кадры: шапка до
          22 %, сюжет в середине, действия с 62 %. Цвет — `--color-bg`
          приложения, чтобы края обоев уходили в его фон, а не в чужой
          чёрный.

          Низ гасится до 0.88, а не до непрозрачного. Сначала стояло 0.93,
          и на экранах-списках («Знания», «Друзья») под последней
          карточкой оставалась чёрная полоса в треть экрана — ровно та
          пустота, ради которой обои и заводились. Дожимать до чёрного тут
          незачем: под самым низом лежит нижняя навигация со своим почти
          непрозрачным фоном. */}
      <div
        className="absolute inset-0"
        style={{
          background: `linear-gradient(to bottom, rgb(11 15 20 / ${topFade}) 0%, rgb(11 15 20 / ${Math.max(midFade, 0.18)}) 26%, rgb(11 15 20 / ${midFade}) 55%, rgb(11 15 20 / ${Math.max(midFade, 0.68)}) 74%, rgb(11 15 20 / ${Math.max(midFade, 0.88)}) 100%)`,
        }}
      />
    </div>
  );
}
