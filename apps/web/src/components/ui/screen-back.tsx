import clsx from 'clsx';
import Link from 'next/link';

/**
 * Выход с экрана — всегда внизу и всегда со словом «Назад».
 *
 * ## Зачем компонент, если это одна строчка разметки
 *
 * Затем, что одной строчкой она была написана десять раз и разошлась.
 * К этому моменту в приложении жили сразу четыре разных выхода: круглая
 * стрелка в шапке (`BackArrow`), надпись «Назад» внизу, надпись «На
 * главную» внизу и «← К режимам» вверху у Alias. Человек, переходя из
 * режима в режим, каждый раз заново искал, где выход и как он называется
 * на этом экране.
 *
 * ## Почему низ, а не шапка
 *
 * Телефон держат одной рукой, палец достаёт нижнюю треть экрана. Выход —
 * не редкое действие: в него упирается любой, кто передумал. Тянуться за
 * ним в угол под чёлку неудобно, и это та же причина, по которой сюда же
 * опущены главные кнопки экранов (см. `.screen-fill`).
 *
 * Одно исключение оставлено осознанно — «Библия». Там список глав и
 * текст главы прокручиваются на несколько экранов, и выход, до которого
 * надо долистать, выходом быть перестаёт: стрелка в шапке там остаётся
 * **вдобавок** к нижнему «Назад», а не вместо него.
 *
 * ## Почему «Назад», а не «На главную»
 *
 * Выход ведёт на уровень выше — из настройки партии в меню режимов, из
 * меню режимов на главную. «На главную» на экране результата дуэли
 * уводило через две ступени сразу, мимо «Играть», куда человек и шёл
 * следующим шагом. Слово описывает действие, а не место, и потому
 * одинаково верно на любом экране.
 *
 * ## Ссылка или кнопка
 *
 * `href` — переход по адресу; `onClick` — возврат к предыдущему шагу
 * внутри одного экрана (меню дуэли, ввод кода). Снаружи это одно и то
 * же действие, и выглядеть оно обязано одинаково, поэтому оба случая
 * живут здесь, а не расходятся по разной разметке.
 *
 * Адрес всегда прямой, а не `history.back()`: экран можно открыть по
 * ссылке от друга, и тогда «назад» увело бы из приложения совсем.
 */
export function ScreenBack(
  props: ({ href: string } | { onClick: () => void }) & {
    /** Куда именно ведёт — для озвучки, вместо голого «назад». */
    label?: string;
    className?: string;
  },
) {
  // Высота в 11 — чтобы палец попадал: до этого выход был просто строкой
  // текста, и промахнуться мимо неё было легче, чем попасть.
  const className = clsx(
    'flex h-11 w-full items-center justify-center gap-1.5 text-sm text-text-secondary transition active:text-text-primary',
    props.className,
  );
  const content = (
    <>
      <span aria-hidden>←</span> Назад
    </>
  );

  if ('href' in props) {
    return (
      <Link href={props.href} aria-label={props.label} className={className}>
        {content}
      </Link>
    );
  }

  return (
    <button type="button" onClick={props.onClick} aria-label={props.label} className={className}>
      {content}
    </button>
  );
}
