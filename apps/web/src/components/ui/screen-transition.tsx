'use client';

import { usePathname } from 'next/navigation';

/**
 * Появление экрана при переходе.
 *
 * Переходы между экранами были мгновенной подменой содержимого: вроде бы
 * быстро, а на деле теряешь, что именно сменилось, — особенно когда
 * шапка и нижнее меню на обоих экранах одинаковые.
 *
 * Здесь короткое появление снизу вверх. Перезапускается сменой `key` на
 * адресе — тем же приёмом, что отсчёт перед дуэлью, и по той же причине:
 * эффект с таймером ради одной анимации это лишняя перерисовка на каждый
 * переход.
 *
 * Движение короткое и небольшое намеренно: длинное появление превращает
 * быстрый переход в ожидание, а `prefers-reduced-motion` его убирает
 * совсем (см. `globals.css`).
 */
export function ScreenTransition({ children }: { children: React.ReactNode }) {
  const pathname = usePathname();
  return (
    <div key={pathname} className="screen-enter">
      {children}
    </div>
  );
}
