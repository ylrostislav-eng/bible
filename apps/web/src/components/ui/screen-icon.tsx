import clsx from 'clsx';

/**
 * Медальон в шапке экрана — стекло, сквозь которое видно обои.
 *
 * ## Что здесь было раньше
 *
 * Одна и та же разметка, написанная на семи экранах вручную:
 * `h-12 w-12 rounded-2xl bg-surface` с иконкой внутри. Непрозрачный
 * серый квадрат поверх картинки режима выглядел заплаткой — единственное
 * место экрана, где обои просто заканчивались без причины.
 *
 * ## Почему стекло здесь работает, а в карточках нет
 *
 * Медальон лежит прямо на фоне, и `backdrop-filter` размывает именно
 * обои. Внутри карточки размывать нечего — там под элементом
 * непрозрачная поверхность, и стекло выродилось бы в светлый
 * прямоугольник (см. `.glass` в `globals.css`).
 *
 * ## Про размер
 *
 * `size` — не украшение: на заглушке «в разработке» медальон крупнее,
 * потому что он там единственный предмет на экране, а в шапке рядом с
 * заголовком крупный спорил бы с ним за внимание.
 */
export function ScreenIcon({
  icon: Icon,
  size = 'md',
  className,
}: {
  icon: React.ComponentType<{ className?: string }>;
  size?: 'md' | 'lg';
  className?: string;
}) {
  return (
    <div
      className={clsx(
        'glass flex shrink-0 items-center justify-center rounded-2xl',
        size === 'lg' ? 'h-16 w-16' : 'h-12 w-12',
        className,
      )}
    >
      <Icon className={clsx('glass-icon text-primary', size === 'lg' ? 'h-8 w-8' : 'h-6 w-6')} />
    </div>
  );
}
