'use client';

import clsx from 'clsx';

/**
 * Пустое место между заголовком и кнопками на коротких экранах.
 *
 * ## Зачем вообще пустота
 *
 * Телефон держат одной рукой, палец достаёт нижнюю треть экрана. На
 * экранах-меню содержимого мало, и без распорки кнопка «Начать игру»
 * оказывалась примерно на трети высоты — до неё приходилось тянуться.
 * Распорка съедает лишнее сверху и уводит действия вниз (см. также
 * `.screen-fill` в `globals.css`).
 *
 * ## Что здесь было раньше
 *
 * Здесь рисовалась приглушённая лампа-маскот в кольцах цвета режима
 * (компонент назывался `ScreenArt`). Она честно закрывала дыру, но
 * одинаково на всех экранах: шесть режимов отличались только оттенком
 * колец. Её заменили обои — `ScreenBackground`, — и лампа стала вторым
 * украшением поверх первого. Возвращать её вместе с обоями не надо: два
 * декоративных слоя в одном месте спорят друг с другом, а не дополняют.
 *
 * ## Что важно не сломать
 *
 * `min-h-0` обязателен: без него flex-элемент не даёт себя сжать меньше
 * содержимого, и на невысоком экране распорка выпихнула бы кнопки за
 * нижний край — ровно та беда, от которой всё затевалось. `flex-1` без
 * своей высоты: на экране, где содержимого много, распорка схлопывается
 * сама.
 */
export function ScreenSpacer({ className }: { className?: string }) {
  return <div aria-hidden className={clsx('min-h-0 flex-1', className)} />;
}
