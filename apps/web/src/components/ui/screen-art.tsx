'use client';

import clsx from 'clsx';
import { usePathname } from 'next/navigation';
import { modeTheme } from '@/lib/mode-theme';
import { OilLampFlame } from './oil-lamp-flame';

/**
 * Тихая картинка в пустоту между заголовком и кнопками.
 *
 * ## Откуда взялась
 *
 * Кнопки на коротких экранах опустили к большому пальцу — и между шапкой
 * и ними образовалась дыра в полэкрана. Дотягиваться стало удобно, а
 * выглядеть стало так, будто содержимое не загрузилось.
 *
 * ## Почему лампа, а не абстрактный узор
 *
 * Лампа — маскот приложения («Да не угасает светильник твой»), он уже
 * встречает на экране завершения партии и в серии дней. Пустое место
 * заполняется тем, что у приложения **уже есть**, а не новой сущностью:
 * узор пришлось бы придумывать, объяснять и потом поддерживать.
 *
 * ## Почему приглушённо и без текста
 *
 * Это фон, а не сообщение. В полную силу лампа спорила бы за внимание с
 * кнопкой, ради которой экран открыт, — поэтому вполсилы и без подписи.
 * Кольца берут цвет режима (`modeTheme`) — тот же, что у сияния вверху
 * экрана, так что дуэль остаётся холоднее одиночной игры и здесь.
 *
 * ## Что важно не сломать
 *
 * `flex-1` — то самое место, которое раньше было пустой распоркой:
 * картинка растягивается ровно на неё и **не задаёт своей высоты**. На
 * экране, где содержимого много, распорка схлопывается, и лампа исчезает
 * сама — ничего не разъезжается и не выталкивает кнопки за край.
 */
export function ScreenArt({ className }: { className?: string }) {
  const { accent } = modeTheme(usePathname());

  return (
    <div
      aria-hidden
      className={clsx(
        // `min-h-0` обязателен: без него flex-элемент не даёт себя сжать
        // меньше содержимого, и на невысоком экране лампа выпихнула бы
        // кнопки вниз — ровно та беда, от которой всё затевалось.
        'flex min-h-0 flex-1 items-center justify-center overflow-hidden py-4',
        className,
      )}
    >
      <div className="relative flex items-center justify-center opacity-60">
        <div
          className="absolute h-40 w-40 rounded-full border"
          style={{ borderColor: `${accent}33` }}
        />
        <div
          className="absolute h-60 w-60 rounded-full border"
          style={{ borderColor: `${accent}1f` }}
        />
        <OilLampFlame size={104} />
      </div>
    </div>
  );
}
