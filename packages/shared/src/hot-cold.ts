/** Одна догадка в списке. */
export interface HotColdGuess {
  /** Слово так, как его понял разбор ввода. */
  word: string;
  /** Место по близости: 1 — загаданное слово. */
  rank: number;
  /** Открыто подсказкой, а не угадано. */
  revealed?: boolean;
  /** Игрок отметил, что слово должно стоять ближе. */
  disputed?: boolean;
}

export interface HotColdState {
  /** Локальная дата игрока, `ГГГГ-ММ-ДД`. */
  date: string;
  /** Номер партии за день: 0 — слово дня, дальше свободные. */
  round: number;
  /** Свободная партия — своё слово, у каждого игрока своё. */
  free: boolean;
  /** Сложность загаданного слова. У слова дня — тоже, но справочно. */
  level: HotColdLevel;
  /** Сколько опыта свободные партии могут принести сегодня ещё. */
  freeXpLeft: number;
  /** Догадки по возрастанию места — ближайшая сверху. */
  guesses: HotColdGuess[];
  /** Сколько слов участвует в ранжировании: знаменатель для «места». */
  vocabulary: number;
  /**
   * Загадка: род загаданного и Завет — «Загадан человек, Ветхий Завет».
   *
   * Бесплатна и видна с самого начала. Без неё игра начинается с перебора
   * наугад: поле ввода не говорит даже, о чём речь, а слабому в лексике
   * Писания и зацепиться не за что. Направление — не ответ: людей Ветхого
   * Завета в банке десятки.
   */
  riddle: string;
  /** Сколько подсказок уже взято: они не кончаются, но их видно. */
  hintsUsed: number;
  /**
   * Что даст следующая подсказка — чтобы решать до нажатия, а не после.
   * `null` только у законченной партии: пока идёт игра, подсказка есть
   * всегда.
   */
  nextHint: { kind: HotColdHintKind; promise: string } | null;
  /**
   * Открытые подсказки-факты: длина с первой буквой и описание. Соседние
   * слова сюда не попадают — они ложатся в общий список догадок, потому
   * что там им и место: у них есть место в рейтинге.
   */
  hints: { kind: HotColdHintKind; text: string }[];
  /** Сдался: слово показано, партия закончена, награды нет. */
  gaveUp: boolean;
  /** Сколько ещё раз можно сказать «должно быть ближе». */
  disputesLeft: number;
  solved: boolean;
  finished: boolean;
  /** Награда, если угадать прямо сейчас. */
  rewardIfSolvedNow: HotColdReward;
  /** Появляется только в конце: до этого ответ клиенту не уезжает. */
  word: string | null;
  gloss: string | null;
  /** Десятка ближайших слов — разбор после игры. */
  closest: HotColdGuess[] | null;
  earned: HotColdReward | null;
}

export interface HotColdReward {
  xp: number;
  coins: number;
}

export interface HotColdGuessResult {
  state: HotColdState;
  /** Место только что введённого слова, `null` — если слово не опознано. */
  rank: number | null;
  /** Что пришлось починить во вводе: раскладку или опечатку. */
  fix: 'none' | 'layout' | 'typo';
  /** Как игра поняла ввод — показывается, если пришлось чинить. */
  understood: string | null;
  /** Это слово уже называли. */
  repeat: boolean;
}

/**
 * Награда за день.
 *
 * Считается по числу догадок, а не по времени: время в такой игре мерить
 * нечестно — человек может отложить телефон на середине и вернуться через
 * час, и это не значит, что он играл хуже.
 */
const REWARD_STEPS: { upTo: number; xp: number; coins: number }[] = [
  { upTo: 10, xp: 60, coins: 30 },
  { upTo: 25, xp: 45, coins: 22 },
  { upTo: 50, xp: 32, coins: 16 },
  { upTo: 100, xp: 22, coins: 11 },
  { upTo: Infinity, xp: 14, coins: 7 },
];

/**
 * Какую долю оставшейся награды забирает подсказка.
 *
 * Именно оставшейся, а не изначальной. Отнималось от изначальной: сначала
 * по четверти при трёх подсказках, потом по шестой части при пяти. Пока
 * подсказки были ограничены, разница не вылезала; теперь они не кончаются,
 * и вычитание доходило бы до нуля — живая проверка показала обрыв с десяти
 * очков на шестой подсказке до одного на седьмой. А партия, из которой
 * больше нечего вынести, не доигрывается, а бросается — то есть прежняя
 * цена гнала ровно туда, откуда мы уводили игрока подсказками.
 *
 * Доля от остатка не доходит до нуля никогда и объясняется одной фразой:
 * каждая подсказка забирает шестую часть того, что осталось. Пять подсказок
 * оставляют две пятых награды, десять — шестую часть, и всё это время есть
 * что терять, а значит, есть зачем угадывать.
 */
const HINT_PENALTY = 1 / 6;

export function hotColdReward(guessCount: number, hintsUsed: number): HotColdReward {
  const step =
    REWARD_STEPS.find((candidate) => guessCount <= candidate.upTo) ??
    REWARD_STEPS[REWARD_STEPS.length - 1];
  const share = Math.pow(1 - HINT_PENALTY, hintsUsed);
  return {
    xp: Math.max(1, Math.round(step.xp * share)),
    coins: Math.max(1, Math.round(step.coins * share)),
  };
}

/** «12 попыток», «3 попытки», «1 попытка». */
export function hotColdAttemptsLabel(count: number): string {
  const tens = count % 100;
  const ones = count % 10;
  if (ones === 1 && tens !== 11) return `${count} попытка`;
  if (ones >= 2 && ones <= 4 && (tens < 10 || tens >= 20)) return `${count} попытки`;
  return `${count} попыток`;
}

/** Строка, которой игрок хвастается друзьям. */
export function hotColdShareText(input: {
  solved: boolean;
  guessCount: number;
  hintsUsed: number;
}): string {
  const attempts = hotColdAttemptsLabel(input.guessCount);
  if (!input.solved) return `Горячо-холодно: сегодня не поддалось — ${attempts}`;
  const hints = input.hintsUsed > 0 ? `, подсказок ${input.hintsUsed}` : '';
  return `Горячо-холодно: ${attempts}${hints}`;
}
