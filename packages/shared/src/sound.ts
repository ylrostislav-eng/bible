/**
 * Звук в приложении: что звучит и чем это выключается.
 *
 * Приложение было немым, и это заметно: победа, ошибка, сгоревшее слово —
 * всё происходит молча, и события, ради которых играют, проходят мимо
 * внимания. Звук здесь не украшение, а вторая дорожка к тому же смыслу.
 *
 * Отсюда и границы, записанные сразу, чтобы не спорить о них потом:
 *
 * - **Звук ничего не заменяет.** Всё, что сказано звуком, должно быть
 *   видно и глазами: половина играет без звука, а кто-то не слышит вовсе.
 * - **Ничего не звучит само.** Первый звук — только после действия
 *   игрока: браузер и не даст иначе, но дело не в браузере.
 * - **Музыка по умолчанию выключена.** Незапрошенная музыка в транспорте
 *   или на работе ощущается как поломка, а не как атмосфера. Звуки —
 *   наоборот, включены: они короткие и отвечают на нажатие.
 */

/** Что вообще умеет звучать. Имя — по событию, а не по звуку. */
export const SOUND_NAMES = [
  /** Нажатие: любая кнопка, которая что-то делает. */
  'tap',
  /** Верный ответ. */
  'correct',
  /** Неверный ответ. */
  'wrong',
  /** Награда: опыт, монеты, уровень. */
  'reward',
  /** Тик последних секунд. */
  'tick',
  /** Партия началась. */
  'start',
  /** Ход соперника — короткий и тихий, чтобы не спорил с набором текста. */
  'opponent',
  /** Слово сгорело: не успели. */
  'burnt',
  'win',
  'lose',
  'draw',
] as const;

export type SoundName = (typeof SOUND_NAMES)[number];

/** Громкость по умолчанию: слышно, но не громче уведомлений системы. */
export const SOUND_VOLUME_DEFAULT = 70;
export const SOUND_VOLUME_MIN = 0;
export const SOUND_VOLUME_MAX = 100;

/** Настройки звука в профиле — они же приходят на клиент. */
export interface SoundSettings {
  soundEnabled: boolean;
  musicEnabled: boolean;
  hapticsEnabled: boolean;
  /** 0–100. Общая для звуков и музыки: две ручки никто не крутит. */
  soundVolume: number;
}

export const SOUND_SETTINGS_DEFAULT: SoundSettings = {
  soundEnabled: true,
  musicEnabled: false,
  hapticsEnabled: true,
  soundVolume: SOUND_VOLUME_DEFAULT,
};
