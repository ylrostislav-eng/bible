/**
 * Дуэль «горячо-холодно»: двое ищут одно слово наперегонки.
 *
 * Соло-режим силён обратной связью, но у него нет второго человека, и
 * через неделю он превращается в кроссворд: интересно, но не тянет
 * вернуться. Здесь то же самое поле, но напротив сидит живой соперник.
 *
 * ## Главное правило: числа видно, слова — нет
 *
 * Каждый видит, на каком месте стоят слова противника, но не сами слова.
 * Это не половинчатость, а суть режима. Показать слова — значит отдать
 * игру: соперник просто перепишет чужой список и обгонит на один ход.
 * Не показывать ничего — значит играть в одиночку рядом с кем-то.
 *
 * А голое число давит именно так, как надо. Ты стоишь на 400, у него
 * вдруг 12 — ты знаешь, что он почти нашёл, знаешь, что времени нет, и не
 * знаешь, куда он смотрит. Отыграться можно только собственной головой.
 */

/** Что сейчас с дуэлью. */
export type HotColdDuelStatus =
  | 'WAITING'
  /** Оба на месте, но игра не началась: каждый жмёт «готов». */
  | 'READY_CHECK'
  | 'IN_PROGRESS'
  | 'FINISHED'
  | 'ABANDONED';

/** Адрес WebSocket-комнаты дуэли. */
export const HOT_COLD_DUEL_WS_NAMESPACE = '/hot-cold-duel';

/** Что шлёт клиент. */
export const HOT_COLD_DUEL_WS_EVENTS = {
  join: 'duel:join',
  guess: 'duel:guess',
  surrender: 'duel:surrender',
  /** «Я готов» перед стартом. */
  ready: 'duel:ready',
  /** Забрать победу, когда соперник ушёл и не вернулся. */
  claim: 'duel:claim',
} as const;

/** Что шлёт сервер. */
export const HOT_COLD_DUEL_WS_SERVER_EVENTS = {
  state: 'duel:state',
  /** Ход противника — чтобы подсветить число, а не перерисовать весь экран. */
  opponentMoved: 'duel:opponent-moved',
  /** Ваше слово сгорело: не успели за отведённые секунды. */
  burnt: 'duel:burnt',
  error: 'duel:error',
} as const;

/**
 * Сколько дуэль ждёт второго игрока, прежде чем считаться брошенной.
 *
 * Достаточно, чтобы позвать друга в мессенджере и дождаться, пока он
 * откроет приложение; недостаточно, чтобы вчерашние приглашения копились
 * в списке.
 */
export const HOT_COLD_DUEL_WAIT_MS = 10 * 60_000;

/**
 * Сколько дуэль живёт без единого хода с обеих сторон, прежде чем её
 * закрывают.
 *
 * Не таймер партии: игра сама по себе может идти долго, и торопить в ней
 * нечего. Это про случай, когда оба закрыли вкладку и не вернутся, — иначе
 * такие дуэли висели бы у обоих в «активных» вечно.
 */
export const HOT_COLD_DUEL_IDLE_MS = 30 * 60_000;

/**
 * Сколько слов даётся каждому за партию.
 *
 * Без предела дуэль могла тянуться бесконечно: если слово не даётся
 * обоим, кончить её нечем — разве что сдаться или уйти.
 *
 * Было тридцать — и это оказалось мало: слово сгорает и от молчания тоже,
 * поэтому счётчик тратится быстрее, чем кажется, и партия обрывалась
 * ровно там, где обычно и нащупывается тема. Пятьдесят держат ту же
 * границу — «либо нашёл направление, либо ходишь по кругу», — но не
 * подрезают того, кто думает.
 *
 * Попытка тратится только на слово, которое игра поняла и которого ещё
 * не было: за опечатку и за повтор счётчик не двигается, как и в
 * одиночной игре.
 */
export const HOT_COLD_DUEL_MAX_GUESSES = 50;

/**
 * Сколько времени даётся на одно слово.
 *
 * Не успел — слово сгорает: счётчик уменьшается, будто ход был сделан
 * впустую. Это меняет саму игру: сидеть и перебирать варианты в голове
 * больше нельзя, надо писать.
 *
 * Было двадцать секунд, стало тридцать: двадцати хватало набрать уже
 * придуманное, но не хватало придумать. Игра при этом превращалась из
 * «думай быстро» в «печатай быстро», а это другое умение и не то, ради
 * чего в неё играют.
 *
 * Часы идут на сервере, а не в браузере. Иначе достаточно перевести
 * системное время или просто закрыть вкладку, чтобы они остановились.
 *
 * Часы не останавливаются и когда игрок ушёл: он тратит слова так же, как
 * если бы сидел и молчал. Это честно — соперник-то ждёт.
 */
export const HOT_COLD_DUEL_SECONDS_PER_GUESS = 30;

/**
 * Сколько длится отсчёт «3-2-1-поехали» после того, как оба готовы.
 *
 * Раньше партия начиналась в ту же секунду, когда соперник находился, и
 * часы шли, пока человек ещё читал, что вообще происходит. Три секунды
 * стоят ровно затем, чтобы взгляд успел добраться до поля ввода.
 *
 * Момент старта считает сервер и отдаёт клиенту временем, а не числом
 * секунд: число устареет, пока летит по сети, а от момента отсчитывать
 * можно точно — с поправкой на часы устройства, как везде в дуэли.
 */
export const HOT_COLD_DUEL_COUNTDOWN_MS = 3_000;

/**
 * Во сколько раз меньше очков за победу, если слово так и не нашлось.
 *
 * Правило проще формулируется не через попытки, а через результат:
 * **нашёл слово — полные очки, победил, не найдя, — половина.** Под это
 * одно правило подходят все случаи сразу: кончились попытки у обоих,
 * соперник сдался, соперник ушёл. Во всех трёх слово осталось
 * неразгаданным, и победа тут по очкам, а не в чистую.
 */
export const HOT_COLD_DUEL_POINTS_SHARE = 0.5;

/**
 * Сколько соперника нет на связи, прежде чем победу можно забрать.
 *
 * Без этого у партии оставался тупик: человек закрыл вкладку, а второй
 * сидит и ждёт — сдаваться не за что, доиграть не с кем, а уборка закроет
 * партию только через полчаса. Двух минут хватает, чтобы отличить
 * ушедшего от того, у кого моргнула связь или кто на секунду переключился
 * в другое приложение.
 *
 * Победа именно **забирается кнопкой**, а не начисляется сама: сервер не
 * знает, ушёл человек навсегда или сейчас вернётся, а оставшийся игрок
 * знает и решает сам.
 */
export const HOT_COLD_DUEL_AWAY_MS = 2 * 60_000;

/**
 * Подсказок в дуэли нет — намеренно.
 *
 * В одиночной игре подсказка стоит четверти награды, и это честный обмен.
 * В гонке цена другая: подсказка приближает к ответу быстрее, чем любой
 * ход, а расплата — в очках, которые всё равно достаются победителю. То
 * есть брать её было бы обязательно, а «обязательная кнопка» — это не
 * выбор, а лишнее нажатие.
 */
export const HOT_COLD_DUEL_HINTS = 0;

/** Рейтинг за исход. Те же числа, что в дуэли по вопросам. */
export const HOT_COLD_DUEL_WIN_RATING = 10;
export const HOT_COLD_DUEL_LOSS_RATING = -5;

/**
 * Какую долю обычной награды получает проигравший.
 *
 * Не ноль: он играл, думал и часто подошёл близко. Но и не поровну —
 * иначе исход перестаёт что-либо значить.
 */
export const HOT_COLD_DUEL_LOSER_SHARE = 0.3;

/** Свои догадки: со словами. */
export interface HotColdDuelGuess {
  word: string;
  rank: number;
}

/**
 * Противник — только то, что можно показать.
 *
 * Здесь нет и не должно появиться поля со словами. Если оно однажды
 * понадобится (например, в разборе после игры), его надо заполнять
 * отдельно и только когда дуэль закончена.
 */
export interface HotColdDuelOpponent {
  userId: string;
  /** Пусто, пока человек не прошёл онбординг, — как и везде в приложении. */
  nickname: string | null;
  avatarUrl: string | null;
  /** Места его слов по порядку ходов. Сами слова — никогда. */
  ranks: number[];
  /** Лучшее место, оно же «насколько он близко». */
  bestRank: number | null;
  guessCount: number;
  /** Сколько слов у него осталось. Число, а не слово, — показывать можно. */
  guessesLeft: number;
  solved: boolean;
  surrendered: boolean;
  /** Нажал «готов» перед стартом. Видно обоим — в этом весь смысл. */
  ready: boolean;
  /** На связи ли он прямо сейчас. */
  online: boolean;
}

export interface HotColdDuelReward {
  xp: number;
  coins: number;
  ratingDelta: number;
  ratingCapped: boolean;
}

export interface HotColdDuelState {
  id: string;
  status: HotColdDuelStatus;
  /** Код, которым зовут второго. Показывается, пока ждём. */
  inviteCode: string;
  /**
   * Партия открыта для подбора: соперника ищет игра, а не игрок.
   *
   * Экран ждёт по-разному — «ищем соперника» и «продиктуйте код другу»
   * говорят человеку разное о том, чего он ждёт и сколько это займёт.
   */
  open: boolean;
  /** Сколько слов участвует в ранжировании: знаменатель для «места». */
  vocabulary: number;

  /** Вы нажали «готов». */
  youReady: boolean;
  /**
   * Когда партия начнётся, ISO-время сервера. Заполнено только на время
   * отсчёта; после старта — `null`.
   *
   * Момент, а не «осталось секунд»: число устареет, пока летит по сети.
   */
  startsAt: string | null;

  /** Свои догадки — со словами, ближайшая сверху. */
  guesses: HotColdDuelGuess[];
  bestRank: number | null;
  /** Сколько слов осталось у вас. */
  guessesLeft: number;
  /**
   * Когда сгорит текущее слово, ISO-время сервера. `null` — часы не идут:
   * партия ещё не началась, уже кончилась или слова у вас вышли.
   *
   * Время, а не «осталось секунд»: пока число летит по сети, оно
   * устаревает, а от момента отсчитывать можно точно.
   */
  deadlineAt: string | null;
  /**
   * Время сервера в момент отправки.
   *
   * Нужно ровно затем, чтобы обратный отсчёт не зависел от часов на
   * устройстве. Они бывают сбиты на минуты и на часы, и без этой поправки
   * игрок с неверными часами видел бы «осталось −40 секунд» или, хуже,
   * вечные двадцать.
   */
  serverNow: string;
  solved: boolean;
  surrendered: boolean;

  opponent: HotColdDuelOpponent | null;
  /** Соперника нет так долго, что победу можно забрать. */
  canClaimWin: boolean;

  /**
   * Кто победил. Пусто, пока идёт игра, — и пусто же при ничьей, когда
   * партия уже закончена. Различать эти два случая надо по `status`.
   */
  winnerId: string | null;
  /** Загаданное слово — только после конца. */
  word: string | null;
  gloss: string | null;
  /** Что начислено лично вам. Появляется в конце. */
  reward: HotColdDuelReward | null;
}

/**
 * Что сказать про исход.
 *
 * Способов закончить партию пять, и человек должен понимать, который из
 * них случился именно с ним: «вы проиграли» после того, как соперник
 * просто ушёл, — это неправда, за которую обидно.
 */
export function hotColdDuelOutcomeLabel(state: HotColdDuelState, myUserId: string): string {
  if (state.status === 'ABANDONED') return 'Дуэль не состоялась';
  if (state.status !== 'FINISHED') return '';

  // Ничья: партия закончена, а победителя нет. Так кончается брошенная
  // обоими партия, в которой никто не подошёл ближе другого.
  if (state.winnerId === null) return 'Ничья: подошли одинаково близко';

  if (state.winnerId === myUserId) {
    if (state.solved) return 'Вы нашли первым';
    if (state.opponent?.surrendered) return 'Соперник сдался';
    if (state.guessesLeft === 0) return 'Слов не осталось — вы были ближе';
    return 'Соперник не вернулся — победа ваша';
  }
  if (state.surrendered) return 'Вы сдались';
  if (state.opponent?.solved) return 'Соперник нашёл первым';
  if (state.guessesLeft === 0) return 'Слов не осталось — соперник был ближе';
  return 'Вы не вернулись к партии вовремя';
}

/**
 * Полные ли очки за эту победу.
 *
 * Слово нашлось — да; победа без разгаданного слова — половина. Считается
 * по состоянию, а не хранится отдельно: одно правило, один источник.
 */
export function hotColdDuelFullPoints(state: HotColdDuelState): boolean {
  return state.solved || state.opponent?.solved === true;
}

/** Строка, которой хвастаются друзьям. Слово в ней не называется. */
export function hotColdDuelShareText(input: {
  won: boolean;
  guessCount: number;
  opponentGuessCount: number;
}): string {
  return input.won
    ? `Горячо-холодно, дуэль: нашёл за ${input.guessCount} против ${input.opponentGuessCount}`
    : `Горячо-холодно, дуэль: не успел — ${input.guessCount} попыток`;
}
