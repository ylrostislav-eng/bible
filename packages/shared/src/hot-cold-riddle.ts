/**
 * Загадка и общие подсказки «Горячо-холодно»: куда думать.
 *
 * Игра честно трудная для того, кто не силён в лексике Писания: поле для
 * ввода не подсказывает даже, о чём вообще речь, и человек начинает с
 * перебора наугад. Отсюда две вещи.
 *
 * **Загадка** видна сразу и бесплатно. Она называет род загаданного и
 * Завет — «загадан человек, Ветхий Завет». Это направление, а не ответ:
 * людей Ветхого Завета в банке десятки, сузить до одного по такой строке
 * нельзя, но и в пустоту больше не тычешься.
 *
 * **Общие подсказки дуэли** идут лестницей и ни одна не опирается на
 * названные слова: в гонке подсказка «вдвое ближе твоего лучшего» была бы
 * не помощью, а форой тому, кто и так впереди.
 *
 * Первые две называют **соседние по смыслу слова** — сначала дальние, потом
 * ближние, — и это главное отличие от того, что было. Сначала ступенями
 * были раздел Писания и книга: «искать в исторических книгах». Владелец
 * сказал прямо, и он прав: тому, кто не силён в Писании, такая строка не
 * говорит ничего, думать по ней некуда. «Рядом стоят: рыбак, лодка, море»
 * понятно любому и показывает именно сторону, а не полку в библиотеке.
 * Третья ступень — форма слова; дальше идти нельзя, следующим шагом было бы
 * описание, а оно и есть ответ.
 *
 * Сами соседние слова считает сервер по тому же ранжированию, что и вся
 * игра, поэтому текст ступеней собирается там (`HotColdDuelService`), а
 * здесь — только то, что не зависит от словаря.
 */

/** Что именно загадано — из банка слов. */
export interface HotColdSecretFacts {
  /** `AliasCategory`: PERSON, PLACE, EVENT, OBJECT, CONCEPT, PARABLE, IDIOM. */
  category: string;
  /** `AliasTestament`: OLD, NEW, BOTH. */
  testament: string;
  /** Книга Писания, 1–66. Пусто у сквозных слов вроде «покаяние». */
  bookId: number | null;
  /** Встречается в тексте часто — считается по числу эпизодов. */
  frequent: boolean;
  /** Само слово. Наружу не уезжает: нужно только для подсказки о форме. */
  word: string;
}

