/**
 * Длина слова и первая буква.
 *
 * Самая сильная из подсказок, которая всё ещё не ответ: сужает перебор в
 * разы, но назвать слово за игрока не может. Живёт здесь, а не в сервисе,
 * потому что одинаково нужна и одиночной игре, и дуэли.
 */
export function hotColdShapeHint(word: string): string {
  const clean = word.trim();
  const first = clean.charAt(0).toUpperCase();
  return `Слово из ${clean.length} ${lettersLabel(clean.length)}, начинается на «${first}»`;
}

/** После «из» всё в родительном: одной буквы, двух букв, пяти букв. */
function lettersLabel(count: number): string {
  return count % 10 === 1 && count % 100 !== 11 ? 'буквы' : 'букв';
}
