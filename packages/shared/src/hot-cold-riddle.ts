/**
 * Каким местом отзываются слова рода.
 *
 * Не первым десятком: род — это направление, а не ответ, и человек,
 * написавший «человек», не должен видеть «почти угадал». Сороковое место
 * читается как уверенное «горячо», и этого ровно достаточно.
 */
export const HOT_COLD_KIN_PLACE = 40;

/** Строка-загадка, видная с самого начала и бесплатно. */
export function hotColdRiddle(facts: HotColdSecretFacts): string {
  const what = CATEGORY_PHRASE[facts.category] ?? 'Загадано слово';
  const where = TESTAMENT_PHRASE[facts.testament] ?? 'Писание';
  return facts.testament === 'BOTH' ? `${what} — ${where}` : `${what}, ${where}`;
}

