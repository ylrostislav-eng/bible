/**
 * Загадка и общие подсказки «Горячо-холодно»: куда думать.
 *
 * Игра честно трудная для того, кто не силён в лексике Писания: поле для
 * ввода не подсказывает даже, о чём вообще речь, и человек начинает с
 * перебора наугад. Отсюда две вещи.
 *
 * **Загадка** видна сразу и бесплатно. Она называет род загаданного и
 * Завет — «загадан человек, Ветхий Завет». Это направление, а не ответ:
 * людей Ветхого Завета в банке десятки, сузить до одного по такой строке
 * нельзя, но и в пустоту больше не тычешься.
 *
 * **Общие подсказки дуэли** идут лестницей и ни одна не опирается на
 * названные слова: в гонке подсказка «вдвое ближе твоего лучшего» была бы
 * не помощью, а форой тому, кто и так впереди. Здесь все три — про само
 * загаданное слово, одинаковые для обоих, и каждая следующая ближе
 * предыдущей: раздел Писания → книга → форма слова. Дальше идти нельзя:
 * следующим шагом было бы описание, а оно и есть ответ.
 *
 * Тексты собираются из того, что и так лежит в банке слов (`AliasWord`):
 * род, Завет, место в Писании. Ничего дописывать руками не нужно — иначе
 * 259 загадок пришлось бы сочинять, и половина вышла бы хуже случайной.
 */

import { BIBLE_BOOKS } from './bible';

/** Что именно загадано — из банка слов. */
export interface HotColdSecretFacts {
  /** `AliasCategory`: PERSON, PLACE, EVENT, OBJECT, CONCEPT, PARABLE, IDIOM. */
  category: string;
  /** `AliasTestament`: OLD, NEW, BOTH. */
  testament: string;
  /** Книга Писания, 1–66. Пусто у сквозных слов вроде «покаяние». */
  bookId: number | null;
  /** Встречается в тексте часто — считается по числу эпизодов. */
  frequent: boolean;
  /** Само слово. Наружу не уезжает: нужно только для подсказки о форме. */
  word: string;
}

/** Род загаданного — целой фразой, чтобы не мучиться с согласованием. */
const CATEGORY_PHRASE: Record<string, string> = {
  PERSON: 'Загадан человек',
  PLACE: 'Загадано место',
  EVENT: 'Загадано событие',
  OBJECT: 'Загадан предмет',
  CONCEPT: 'Загадано понятие',
  PARABLE: 'Загадана притча',
  IDIOM: 'Загадано выражение',
};

const TESTAMENT_PHRASE: Record<string, string> = {
  OLD: 'Ветхий Завет',
  NEW: 'Новый Завет',
  BOTH: 'встречается в обоих Заветах',
};

/**
 * Разделы канона — то, чем меряют «в какой стороне» люди, читающие
 * Писание. «Книга 14» не говорит ничего, «исторические книги» говорит
 * всё, что нужно на первом шаге.
 */
function sectionOf(bookId: number): string {
  if (bookId <= 5) return 'Пятикнижие';
  if (bookId <= 17) return 'исторические книги';
  if (bookId <= 22) return 'учительные книги';
  if (bookId <= 39) return 'книги пророков';
  if (bookId <= 44) return 'Евангелия и Деяния';
  if (bookId <= 65) return 'послания апостолов';
  return 'Откровение';
}

/** Строка-загадка, видная с самого начала и бесплатно. */
export function hotColdRiddle(facts: HotColdSecretFacts): string {
  const what = CATEGORY_PHRASE[facts.category] ?? 'Загадано слово';
  const where = TESTAMENT_PHRASE[facts.testament] ?? 'Писание';
  return facts.testament === 'BOTH' ? `${what} — ${where}` : `${what}, ${where}`;
}

/**
 * Сколько общих подсказок можно взять на двоих за партию.
 *
 * Три, и это не круглое число ради круглого: четвёртой ступени, которая
 * была бы ближе формы слова и при этом не ответом, просто нет.
 */
export const HOT_COLD_DUEL_HINT_LIMIT = 3;

/** Ступени: чем дальше, тем ближе к слову — но не до самого слова. */
export function hotColdDuelHint(step: number, facts: HotColdSecretFacts): string {
  if (step <= 0) {
    if (facts.bookId === null) {
      // У сквозных слов одной книги нет, и врать про неё нельзя. Зато
      // «проходит через всё Писание» — само по себе направление: значит,
      // это не имя и не место, а то, о чём говорят везде.
      return 'Слово проходит через всё Писание — оно не привязано к одной книге';
    }
    return `Искать в разделе: ${sectionOf(facts.bookId)}`;
  }
  if (step === 1) {
    const book = BIBLE_BOOKS.find((item) => item.id === facts.bookId);
    if (!book) {
      return facts.frequent
        ? 'В тексте встречается часто — мимо такого слова не пройдёшь'
        : 'В тексте встречается редко — это не самое ходовое слово';
    }
    return `Книга: ${book.name}`;
  }
  return hotColdShapeHint(facts.word);
}

/**
 * Длина слова и первая буква.
 *
 * Самая сильная из подсказок, которая всё ещё не ответ: сужает перебор в
 * разы, но назвать слово за игрока не может. Живёт здесь, а не в сервисе,
 * потому что одинаково нужна и одиночной игре, и дуэли.
 */
export function hotColdShapeHint(word: string): string {
  const clean = word.trim();
  const first = clean.charAt(0).toUpperCase();
  return `Слово из ${clean.length} ${lettersLabel(clean.length)}, начинается на «${first}»`;
}

/** После «из» всё в родительном: одной буквы, двух букв, пяти букв. */
function lettersLabel(count: number): string {
  return count % 10 === 1 && count % 100 !== 11 ? 'буквы' : 'букв';
}
